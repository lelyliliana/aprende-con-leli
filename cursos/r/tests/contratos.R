source("src/curso.R", encoding = "UTF-8")
source("proyecto/analizar.R", encoding = "UTF-8")
cuenta <- 0L; grupos <- 0L
exigir <- function(ok) { stopifnot(isTRUE(ok)); cuenta <<- cuenta + 1L }
rechaza <- function(expr) {
  r <- tryCatch(force(expr), error = function(e) e)
  exigir(inherits(r, "error"))
}
grupo <- function(nombre) { grupos <<- grupos + 1L; cat("OK", nombre, "\n") }
d <- leer_encuesta()
exigir(nrow(d) == 36L && !anyDuplicated(d$id))
exigir(sum(is.na(d$horas_semana)) == 3L && sum(is.na(d$satisfaccion)) == 2L)
grupo("Lectura, identidad y faltantes")
m <- rbind(d, d[1, ]); rechaza(validar_encuesta(m)); exigir(nrow(d) == 36L)
rechaza(validar_encuesta(d[-1])); grupo("Duplicados y esquema")
for (campo in c("edad", "horas_semana", "puntaje")) {
  m <- d; m[[campo]][1] <- -1; rechaza(validar_encuesta(m))
  m[[campo]][1] <- Inf; rechaza(validar_encuesta(m))
}
m <- d; m$grupo[1] <- "C"; rechaza(validar_encuesta(m))
m <- d; m$satisfaccion[1] <- "otra"; rechaza(validar_encuesta(m))
grupo("Dominios y valores no finitos")
m <- d; m$horas_semana[m$grupo == "A"] <- NA_real_; r <- resumir_encuesta(m)
exigir(r$n_horas[r$grupo == "A"] == 0L && is.na(r$media_horas[r$grupo == "A"]))
exigir(!is.nan(r$media_horas[r$grupo == "A"]))
m <- d; m$puntaje[1] <- NA_real_; rechaza(validar_encuesta(m))
grupo("Denominadores y grupo sin mediciones")
limpio <- limpiar_entrada()
exigir(identical(limpio$validas$id, c("S01", "S02", "S05")))
exigir(sum(limpio$incidencias$duplicada) == 1L && sum(limpio$incidencias$invalida) == 4L)
exigir(limpio$original$horas_semana[2] == "7,5" && limpio$validas$horas_semana[2] == 7.5)
carpeta <- tempfile("contratos-r-"); dir.create(carpeta); archivo <- file.path(carpeta, "entrada.csv")
m <- limpio$original; m$puntaje[3] <- "81"
write.csv(m, archivo, row.names = FALSE, na = "", fileEncoding = "UTF-8")
rechaza(limpiar_entrada(archivo)); grupo("Limpieza trazable y contradicción")
m <- d; m$id[1] <- "Á-01"
write.csv(m, archivo, row.names = FALSE, na = "", fileEncoding = "UTF-8")
exigir(identical(leer_encuesta(archivo), m)); grupo("Ida y vuelta UTF-8")
catalogo <- read.csv("datos/grupos.csv", fileEncoding = "UTF-8")
r <- dplyr::left_join(d, catalogo, by = "grupo", relationship = "many-to-one")
exigir(nrow(r) == nrow(d) && identical(r$id, d$id))
rechaza(dplyr::left_join(d, rbind(catalogo, catalogo[1, ]), by = "grupo", relationship = "many-to-one"))
m <- d; m$grupo[1] <- "C"; exigir(nrow(dplyr::anti_join(m, catalogo, by = "grupo")) == 1L)
grupo("Cardinalidad y claves ausentes")
ancha <- data.frame(id = c("A", "B"), antes = c(50, 60), despues = c(70, 80))
larga <- tidyr::pivot_longer(ancha, c(antes, despues), names_to = "momento", values_to = "puntaje")
exigir(nrow(larga) == 4L && length(unique(larga$id)) == 2L)
r <- tidyr::pivot_wider(larga, names_from = momento, values_from = puntaje)
exigir(isTRUE(all.equal(as.data.frame(r), ancha, check.attributes = FALSE)))
grupo("Transformación y unidad de observación")
x <- c(8, 9, 10, 11, 12); r <- t.test(x, mu = 10)
manual <- mean(x) + c(-1, 1) * qt(0.975, df = length(x) - 1) * sd(x) / sqrt(length(x))
exigir(isTRUE(all.equal(unname(r$conf.int[1:2]), manual, check.attributes = FALSE)))
exigir(abs(r$p.value - 1) < 1e-12); grupo("Intervalo y cálculo explícito")
x <- 0:5; y <- 2 + 3 * x + c(1, -1, 0, 0, -1, 1); m <- lm(y ~ x)
exigir(abs(coef(m)[2] - 3) < 1e-10)
exigir(abs(unname(predict(m, data.frame(x = 2.5))) - 9.5) < 1e-10)
grupo("Coeficientes y unidades")
salida <- file.path(carpeta, "valida"); p <- ejecutar_analisis("datos/encuesta.csv", salida)
registro <- jsonlite::read_json(file.path(salida, "registro.json"), simplifyVector = TRUE)
exigir(sum(p$resumen$n) == 36L && registro$filas == 36L && registro$datos_ficticios)
exigir(registro$md5 == unname(tools::md5sum("datos/encuesta.csv")))
exigir(file.info(file.path(salida, "puntajes.svg"))$size > 1000)
exigir(nrow(read.csv(file.path(salida, "resumen.csv"))) == 2L)
grupo("Entrega y registro")
m <- d; m$puntaje[1] <- -1
write.csv(m, archivo, row.names = FALSE, na = "", fileEncoding = "UTF-8")
salida_invalida <- file.path(carpeta, "rechazada")
rechaza(ejecutar_analisis(archivo, salida_invalida)); exigir(!dir.exists(salida_invalida))
unlink(carpeta, recursive = TRUE); grupo("Rechazo antes de escribir")
cat("Grupos de contratos:", grupos, "; comprobaciones:", cuenta, "\n")
